// minimo package path in node_modules
const node_modules_path = '../../node_modules',
  minimo_path = `${node_modules_path}/@massimo-cassandro/minimo`;

const config = {

  // ---------------------------------------------------------------------------
  // BUILD-TOKENS & STYLE-DICTIONARY SETTINGS
  // ---------------------------------------------------------------------------

  // Path to the stylelint config used to lint the generated CSS file
  stylelintConfigPath: '../../stylelint.config.mjs',

  // Output directory for the CSS file generated by Style Dictionary
  buildPath: './',

  // Output filename for the generated CSS file
  destFile: 'custom-properties.css',

  // Source token files — accept paths, globs, or a mix of both.
  // Supported formats: .json, .jsonc, .mjs (must export a DTCG-compliant default object)
  //
  // Legacy (non-DTCG) .json files — e.g. exported from Open Props — are
  // auto-detected and converted to DTCG v5 syntax at parse time, so they can
  // be freely mixed with regular DTCG sources (see README.md). Not covered:
  // .jsonc, reserved for hand-authored DTCG sources. These .json files are
  // parsed with plain JSON.parse (no comments, no trailing commas).
  //
  // A legacy node that is at the same time a token (own value/type) AND a
  // group with nested children (e.g. Open Props' other.ease.out, which has
  // its own value plus out.1 ... out.5) cannot be represented in DTCG v5 —
  // a node with $value is always a leaf. Its own value is moved to a child
  // token named `default` (other.ease.out.default, i.e. --other-ease-out-default),
  // or `base` if a `default` child already exists; if both exist the build
  // fails. References to such a node from the same file are rewritten
  // accordingly; from other files they must use the child name explicitly.
  //
  // WARNING: do not use path.join() to build glob patterns — it may corrupt
  // the pattern syntax. Use template literals instead:
  //   OK:  `${minimo_path}/**/*.{json,mjs}`
  //   NO:  path.join(minimo_path, '/**/*.{json,mjs}')
  //
  // An entry can also be an object `{ src, prefix, transform }` (src: string
  // or array of strings/globs).
  //
  // `prefix`: renders the custom properties of those files with a prefix,
  // e.g. { src: '...open-props...json', prefix: 'op' } turns Open Props'
  // gray.0 into --op-gray-0. Only the property name changes: {references} to
  // those tokens are rendered as var(--op-gray-0), and the JSON output stays
  // unprefixed. 'op', 'op-' and '--op-' are equivalent. Two different
  // prefixes for the same file make the build fail.
  //
  // `transform`: moves/renames token nodes within those files' own tree —
  // e.g. { primary: 'primary.100' } takes whatever is defined at dot-path
  // `primary` and moves it to `primary.100`, BEFORE Style Dictionary resolves
  // {references} or builds the CSS/JSON output (unlike `prefix`, which is a
  // purely cosmetic CSS name change applied after the fact — see
  // build-tokens-src/source-transforms.mjs). Typical use case: a preexisting
  // project (e.g. driven by Figma/Penpot) names its own base color `primary`,
  // while minimo's own tokens reference `{primary.100}` — instead of
  // renaming the property by hand after every build, or hunting down every
  // minimo reference to change it, `transform` fixes the token's own path
  // once, here.
  //   - Both sides of the map use Style Dictionary's own DOT-PATH notation
  //     ('primary.100'), NOT the hyphen-joined custom-property notation
  //     ('primary-100'): token name segments in this project can themselves
  //     contain hyphens (e.g. btn-close), so a hyphen can't reliably tell a
  //     path separator from a literal part of a segment name — a dot can,
  //     since it's already reserved by Style Dictionary as the {reference}
  //     path separator.
  //   - {References} to the OLD path — in the same file or a completely
  //     different one — are rewritten automatically, tree-wide, to the NEW
  //     path once all sources are merged: e.g. every {primary} in the whole
  //     build becomes {primary.100}, whether minimo's own tokens already
  //     wrote {primary.100} directly (no-op) or something else in the
  //     project still says {primary}.
  //   - WARNING: this rewrite is by design file-independent (a bare
  //     {reference} doesn't know which file it "belongs" to) — so if the
  //     SAME source key (e.g. "primary") is given a DIFFERENT destination in
  //     two different files' `transform` maps, each rename itself still
  //     works fine, but {primary} becomes ambiguous: which destination should
  //     it be rewritten to? In that case the automatic rewrite is skipped
  //     for that key (a warning is logged), and every {primary} reference
  //     must be fixed by hand to point at the right one of the two new
  //     paths.
  //   - A source key not found in the file only logs a warning, it does not
  //     fail the build.
  //   - Applies to both the CSS and the JSON output (see JSON TOKENS OUTPUT
  //     below), since both are rebuilt from the token's path, by then already
  //     renamed.
  //
  // Both options work the same way inside sourceModes.
  source: [
    `${minimo_path}/design-tokens/_src/**/*.tokens.{mjs,jsonc}`, // main tokens
    `${minimo_path}/src/**/*.tokens.{mjs,jsonc}`, // components tokens

    // optional extra token source (in this example, openProps, https://open-props.style/)
    // { src: `${node_modules_path}/open-props/open-props.style-dictionary-tokens.json`, prefix: 'op' },

    // your project tokens — e.g. remaps a Figma/Penpot-exported `primary`
    // color to minimo's own `primary.100` naming
    {
      src: './project-tokens/*.{js,mjs,jsonc,json}',
      prefix: 'my-project',
      transform: { primary: 'primary.100' },
    }
  ],

  // Optional light/dark (or other) custom properties split — alternative to
  // `source`. If this key is set (a non-null object), `source` above is
  // ignored: each key is a mode name with its own array of source patterns
  // (same rules as `source`: paths, globs, or a mix).
  //
  // The generated CSS composes all modes into a single destFile:
  //   - the base mode's props (see sourceModesBase below) go in a top-level
  //     `:root { ... }` block, with `color-scheme: <all modes>;` prepended
  //     (e.g. "light dark")
  //   - every other mode's props go in
  //     `@media (prefers-color-scheme: <mode>) { :root { ... } }`, with
  //     `color-scheme: <mode>;` prepended
  // customPropsGroups, mergeCustomProps, addLayer, pxToRem etc. all apply
  // the same way as with a single `source`.
  //
  // Cross-mode references: tokens of a non-base mode can reference tokens
  // defined in the base mode (e.g. a dark token using {color.1} defined in
  // light); it resolves to var(--color-1). The reverse (or between two
  // non-base modes) is not supported and fails with a "reference not
  // defined" error, since the target would be undefined outside its own
  // @media block.
  //
  // The JSON output (see JSON TOKENS OUTPUT below) is produced once per
  // mode, with the mode name appended to each filename, e.g. with
  // jsonDestFile: 'tokens' -> "tokens-light.jsonc", "tokens-dark.jsonc".
  //
  // sample:
  // sourceModes: {
  //   light: [
  //     `${minimo_path}/design-tokens/_src/**/*.tokens.{mjs,jsonc}`,
  //     `${minimo_path}/src/**/*.tokens.{mjs,jsonc}`,
  //     './project-tokens/light/*.{js,mjs,jsonc,json}',
  //   ],
  //   dark: [
  //     './project-tokens/dark/*.{js,mjs,jsonc,json}',
  //   ],
  // },
  sourceModes: null,

  // With sourceModes set, and only if it defines both a `light` and a `dark`
  // key: custom properties present in BOTH — matched by name — are written
  // once as `--name: light-dark(<light-value>, <dark-value>);`, instead of
  // being split across the base mode's top-level block and a
  // `@media (prefers-color-scheme: dark) { ... }` rule.
  //
  // Unaffected:
  //   - any other key in sourceModes besides light/dark (e.g. a third,
  //     custom mode) — always stays on its own
  //     `@media (prefers-color-scheme: <mode>) { ... }` rule
  //   - a property present in only one of `light`/`dark` — stays in its own
  //     mode's block (still behind `@media`, unless that mode happens to be
  //     sourceModesBase)
  //
  // Whenever this option is active (sourceModes has both a light and a dark
  // key), the base mode's `color-scheme` declaration is always normalised to
  // read "light dark [...any other mode]", with light before dark — matching
  // light-dark()'s own (light-value, dark-value) argument order — regardless
  // of the order sourceModes keys were declared in, or of which of the two
  // is configured as sourceModesBase below.
  //
  // Interaction with mergeCustomProps: no special handling needed — the
  // per-mode merge with pre-existing custom properties always runs first;
  // this option then reconciles whatever value ends up in each mode
  // (freshly generated or preserved from a pre-existing file) into
  // light-dark(), matched by name. This also means that re-running a build
  // with this option newly turned on, over a destFile previously generated
  // with it off (classic `@media (prefers-color-scheme: dark)` split) and
  // mergeCustomProps: true, converts the preserved values into light-dark()
  // calls too — as with any mergeCustomProps case, a resulting mismatch is
  // left for you to fix.
  //
  // Default: true. Ignored when sourceModes is not set (null/undefined).
  useLightDarkFunc: true,

  // With sourceModes set: the mode whose declarations go in the top-level
  // `:root { ... }` block, instead of nested inside its own
  // `@media (prefers-color-scheme: <mode>) { ... }` rule (default: the first
  // key of sourceModes, e.g. 'light'). Ignored when sourceModes is not set.
  sourceModesBase: 'light',

  // CSS selector wrapping the generated custom properties block(s), instead
  // of the default `:root`. Applies uniformly whether using a single
  // `source` or `sourceModes` (the base mode's top-level block and every
  // other mode's block nested under its own
  // `@media (prefers-color-scheme: <mode>)` rule all use this same
  // selector). Falsy or blank values fall back to ':root'.
  customPropsSelector: ':where(html)',

  // If true (default), dimension token values expressed in px are converted
  // to rem in the generated CSS. Values in other units (em, %, vh, dvw, ...)
  // are never touched regardless of this option.
  pxToRem: false,

  // Preserves custom properties already present in the CSS destination file
  // (destFile, from a previous build) across rebuilds: their values take
  // priority over the ones generated by this build. Useful to keep manual
  // overrides/additions made directly in the compiled CSS. Ignored if the
  // destFile does not exist yet. Accepted values:
  //   false           - no merge: the destination file is fully regenerated
  //   true (default)  - merge all the sources
  //   array           - strings and/or RegExps matched against the path of the
  //                     token source files (those in `source` or `sourceModes`):
  //                     only the properties generated by a matching file are
  //                     merged, the others are overwritten by the generated value.
  //                     A string matches if contained in the file path.
  //                     An empty array is treated as false.
  //                     e.g. ['/theme.minimo.tokens', /colors\.tokens\.(mjs|jsonc?)$/]
  // With true or an array, properties found only in the pre-existing file (no
  // longer generated, e.g. added by hand) are always kept.
  // Comments at the end of a custom property line are preserved; full-line
  // comments are lost, and a multi-line comment is cut at the end of its first
  // line (and closed, to keep the CSS valid).
  mergeCustomProps: true,

  // Wraps the generated custom properties inside a CSS `@layer` at-rule,
  // e.g. addLayer: 'project' -> `@layer project { :root { ... } }`.
  // Set to null, undefined or false (default) to emit no layer.
  addLayer: false,

  // Named groups of custom properties. Properties whose first hyphen-separated
  // name segment matches one of a group's `prefixes` are pulled out, labelled
  // with the group's `name` and placed at the beginning of the output CSS
  // file, in the order the groups are listed here.
  customPropsGroups: [
    {
      name: 'COLORS',
      prefixes: ['accent', 'primary', 'secondary', 'neutral', 'color'],
    },
    {
      name: 'LAYOUT',
      prefixes: ['body', 'layout'],
    },
    {
      name: 'UI',
      prefixes: ['ui'],
    },
  ],


  // ---------------------------------------------------------------------------
  // JSON TOKENS OUTPUT
  // ---------------------------------------------------------------------------
  // Optional design tokens output, independent of any specific consuming tool
  // Generates one or more json(c) files in addition to the CSS output file —
  // usable in Penpot, Figma (via plugin), Token Studio, or as an alternative
  // to the .mjs source files
  // ---------------------------------------------------------------------------

  // How to handle math expressions in dimension token $values (e.g. "{size.base} * .25"):
  //   'keep'    write the expression unchanged
  //   'calc'    — wrap in CSS calc(): "calc({size.base} * .25)"
  //   'resolve' — (default) evaluate numerically, inheriting the unit from the first referenced token
  //               e.g. {size.base} = 16px, "{size.base} * .25" -> "4px"
  jsonExpression: 'resolve',

  // Output format for the JSON token files: 'jsonc' or 'json'
  //   'jsonc' -> adds a generated-file disclaimer header, uses .jsonc extension
  //   'json'  -> plain JSON, no disclaimer
  jsonFormat: 'jsonc',

  // Output directory for the JSON design token files.
  // Set to null (or omit) to disable json output entirely.
  // In multi-file mode (jsonDestFile: null), all files are written flat in
  // this directory (no subdirectories mirroring the source tree); the build
  // fails with an error if two source files would produce the same filename.
  jsonBuildPath: null, // or './path/to/generated/design-tokens-dir',

  // Base name (without extension) for the aggregated JSON output file.
  // The extension is added automatically based on jsonFormat.
  // Set to null (or omit) to generate one file per .mjs source file instead
  // (all placed flat in jsonBuildPath — see jsonBuildPath above).
  jsonDestFile: null, // or 'tokens' (or else),


  // ---------------------------------------------------------------------------
  // CHECK UNRESOLVED & UNUSED CUSTOM PROPS SETTINGS
  // ---------------------------------------------------------------------------

  // If true, also reports custom properties that are defined (in destFile or
  // an extraCustomPropsFiles entry) but never referenced via var() in any
  // scanned CSS file. Opt-in because it re-runs the Style Dictionary
  // transform pipeline over the token sources to resolve, when possible, the
  // .mjs source file for each unused property. Default: false.
  checkUnused: true,

  // When checkUnused is true: if true (default), custom properties sourced
  // from a token file under node_modules (e.g. a third-party token package)
  // are never reported as unused — the consuming project isn't expected to
  // prune those.
  ignoreUnusedInNodeModules: true,

  // Additional CSS files that define custom properties used in the project
  // but not generated by build-tokens (e.g. third-party libraries)
  extraCustomPropsFiles: [
    // `${node_modules_path}/open-props/open-props.min.css`
  ],

  // Directory containing the CSS files to scan for unresolved custom properties
  dirToCheck: '../../app',

  // Regular expressions for custom property names to exclude from the check.
  // Useful for intentionally private/internal props (e.g. prefixed with --_).
  excludePattern: [
    /^--_/,
  ],
};

